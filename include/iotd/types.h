// ===========================================================================
// iotd/types.h
//
// 这个文件只做一件事：定义整个项目共用的"数据类型"。
//
// 为什么不把这些结构体写进各自的 cpp 里？
// 因为 SensorReading 既被数据源（Mock/串口）产生，又被 DeviceClient 消费，
// 还被 JSON 编码器使用。放在公共头文件里，三方看到的是同一个定义，
// 编译器才能保证它们对内存布局的理解一致。
//
// 这是"C++ 工程化"的第一课：先统一数据类型，再写逻辑。
// ===========================================================================

#pragma once
// #pragma once 的作用：这个头文件在一次编译中只允许被包含一次。
// 没有它，当 A 包含 B、B 又包含 A 时会出现"重复定义"编译错误。

#include <cstdint>
#include <string>

namespace iotd {
// namespace 的作用：把名字关进"iotd"这个盒子里，避免和别人的 SensorReading
// 撞名。 你以后在面试里会被问"为什么 C++ 要有命名空间"——这就是答案。

// ---------------------------------------------------------------------------
// SensorReading：一条传感器读数。这是全项目最核心的数据结构。
// ---------------------------------------------------------------------------
struct SensorReading {
    double temperature_c = 0.0; // 温度，单位摄氏度
    double humidity_pct = 0.0;  // 湿度，单位百分比
    int light_lux = 0;          // 光照，单位勒克斯(lux)
                                // 这里用 int 而不是 int32_t：光照只在 0~几万 之间，
                                // int 在任何平台都够放，不需要关心具体几个字节。
                                // 凡是"要跨平台传输或在程序间传递"的量（如时间戳）
                                // 才必须用固定宽度类型，见下面 timestamp_ms。

    // = 0.0 这种写法叫"默认成员初始化器"（C++11）。
    // 它的作用是：即使你写 SensorReading r; 不做任何初始化，
    // temperature_c 也一定是 0.0，而不是内存里的随机垃圾值。
    // 新手最常见的 bug 之一就是"忘了初始化"——这样写就永远不会犯。
};

// ---------------------------------------------------------------------------
// DeviceMessage：从设备收到的一条完整报文。
// 报文里除了传感器数据，还有"是谁发的"和"什么时候发的"。
// ---------------------------------------------------------------------------
struct DeviceMessage {
    std::string device_id;         // 设备编号，例如 "fish-tank-01"
    std::int64_t timestamp_ms = 0; // Unix 毫秒时间戳
    // 为什么时间戳必须写明是 64 位？因为 int 的大小由平台决定（常见 4 字节，
    // 最大约 21 亿），而毫秒时间戳现在是 1.7 万亿级别，用 int 直接溢出。
    // （你可能听过"2038 年问题"——那是秒级时间戳撞上 32 位上限于 2038 年到期，
    // 毫秒级更早，1970 年 1 月就撞了，所以这里必须自己写清楚。）
    // int64_t 明确表示"8 字节有符号"，换平台也不会变。
    // 这也是上面 #include <cstdint> 唯一的原因。
    SensorReading reading;         // 嵌套一个 SensorReading

    // 结构体嵌套结构体，是表达"一个东西包含另一个东西"的最自然方式。
    // 面试时会问"struct 和 class 的区别"——在 C++ 里只有一个区别：
    // struct 默认成员是 public，class 默认是 private。仅此而已。
};

// ---------------------------------------------------------------------------
// 主题拼接工具：MQTT 的主题形如 dev/{设备号}/up
// 第二阶段接入 MQTT 时会用到，现在先放好。
// ---------------------------------------------------------------------------
inline std::string BuildUpTopic(const std::string &device_id) {
    return "dev/" + device_id + "/up";
}

inline std::string BuildCmdTopic(const std::string &device_id) {
    return "dev/" + device_id + "/cmd";
}

// inline 关键字在这里是必需的。
// 头文件里定义的函数会被每个包含它的 .cpp 各编译一份，
// 链接时就会出现"符号重复定义"。inline 告诉编译器：
// 这些定义是一样的，请只保留一份。
// 面试高频题："头文件里能不能写函数定义？" —— 能，但必须加 inline。

} // namespace iotd
